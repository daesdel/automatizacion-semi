_BORDES = {"hair": 7, "thin": 1, "medium": 2, "thick": 5, "double": 6,
           "dotted": 4, "dashed": 3}
_NUM = {"14": "dd/mm/yyyy", "22": "dd/mm/yyyy hh:mm", "49": "@"}


def _rgb(valor):
    if not valor:
        return None
    valor = str(valor)
    if len(valor) == 8:
        valor = valor[2:]
    return "#" + valor


def _formato(wb, d):
    o = {}
    if d.get("fill"):
        o["bg_color"] = _rgb(d["fill"])
    if d.get("font"):
        o["font_name"] = d["font"]
    if d.get("size"):
        o["font_size"] = d["size"]
    if d.get("bold"):
        o["bold"] = True
    if d.get("color"):
        o["font_color"] = _rgb(d["color"])
    num = str(d.get("num_fmt") or "0")
    if num in _NUM:
        o["num_format"] = _NUM[num]
    for lado, estilo in (d.get("border") or {}).items():
        if estilo in _BORDES:
            o[lado] = _BORDES[estilo]
            color = (d.get("border_color") or {}).get(lado)
            o[lado + "_color"] = _rgb(color) or "#000000"
    al = d.get("align") or {}
    if al.get("horizontal"):
        o["align"] = al["horizontal"]
    if al.get("vertical"):
        o["valign"] = al["vertical"]
    if al.get("wrapText") in ("1", 1, True):
        o["text_wrap"] = True
    return wb.add_format(o)


def crear_formatos(wb):
    """Devuelve (cabecera[1..87], datos[1..87]) listos para xlsxwriter."""
    cab = {i: _formato(wb, CABECERA[i]) for i in range(1, 88)}
    dat = {i: _formato(wb, DATOS[i]) for i in range(1, 88)}
    return cab, dat
